#!/usr/bin/env python3
"""Generate the promo codes, returning customers and their promo usage history for the demo.

Outputs (all committed; rerun this script to regenerate, output is deterministic):
  src/postgres/promo-seed.sql                   current promo codes + past redemptions, for the promotions schema
  src/load-generator/returning_customers.json   who the load generator checks out as

The current promo codes are letters and digits only. Customers who have been with us since
before 2020 also used codes from the old newsletter tool, where marketing typed codes in by
hand ('SUMMER-20%', "XMAS'18", 'CAFÉ15'). Those codes no longer exist, but their
redemptions are still in each customer's history.

Usage: scripts/generate-promo-seed.py
"""

import json
import random
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path

SEED = 20261021
N_CUSTOMERS = 300
FIRST_YEAR = 2015
CURRENT_SYSTEM_YEAR = 2020
NOW = datetime(2026, 10, 1, tzinfo=timezone.utc)

ROOT = Path(__file__).resolve().parent.parent

# (code, percent_off): what checkout accepts today
PROMO_CODES = [
    ("SAVE10", 10),
    ("SAVE25", 25),
    ("WELCOME15", 15),
    ("THANKYOU10", 10),
    ("STARGAZE20", 20),
    ("COMEBACK15", 15),
]

# (code, percent_off, kind): promo types beyond a flat percentage. Not in past redemptions.
NEW_PROMO_CODES = [
    ("LOYALTY5", 5, "loyalty"),
]

# Codes from the old newsletter tool, by year. Only seen in past redemptions.
LEGACY_CODES = {
    2015: ["WELCOME 5", "SPRING*15"],
    2016: ["SUMMER-20%", "BACK2SCHOOL/16", "XMAS'16"],
    2017: ["FRIENDS&FAMILY", "10%OFF", "BLACK FRIDAY!"],
    2018: ["XMAS'18", "CAFÉ15", "NEWYEAR#2018", "SUMMER-25%"],
    2019: ["VALENTINE<3", "SPRING_19", "THANKS:)", "CYBER-MONDAY"],
}

FIRST = [
    "Ada", "Alan", "Grace", "Linus", "Margaret", "Dennis", "Barbara", "Ken", "Frances", "Edsger",
    "Radia", "Donald", "Hedy", "Tim", "Katherine", "John", "Sophie", "Guido", "Anita", "Bjarne",
    "Rosa", "Omar", "Priya", "Mateo", "Aisha", "Chen", "Ingrid", "Kwame", "Lena", "Rafael",
]
LAST = [
    "Lovelace", "Turing", "Hopper", "Torvalds", "Hamilton", "Ritchie", "Liskov", "Thompson",
    "Dijkstra", "Perlman", "Knuth", "Lamarr", "Johnson", "McCarthy", "Wilson", "Cerf", "Clarke",
    "Okafor", "Haddad", "Raman", "Silva", "Bello", "Zhang", "Larsen", "Mensah", "Fischer", "Ortega",
]
MAIL_DOMAINS = ["mail.example", "inbox.example", "post.example"]


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def random_instant(rng, year, not_before):
    start = max(datetime(year, 1, 1, tzinfo=timezone.utc), not_before)
    end = min(datetime(year + 1, 1, 1, tzinfo=timezone.utc), NOW)
    if end <= start:
        return start
    return start + timedelta(seconds=rng.randint(0, int((end - start).total_seconds())))


def main():
    rng = random.Random(SEED)
    current_codes = [c for c, _ in PROMO_CODES]

    customers = []
    redemptions = []  # (email, code, order_id, created_at)
    seen = set()
    while len(customers) < N_CUSTOMERS:
        email = f"{rng.choice(FIRST)}.{rng.choice(LAST)}{rng.randint(1, 99)}@{rng.choice(MAIL_DOMAINS)}".lower()
        if email in seen:
            continue
        seen.add(email)
        # About 40% of returning customers have been around since the newsletter days.
        if rng.random() < 0.4:
            since = rng.randint(FIRST_YEAR, CURRENT_SYSTEM_YEAR - 1)
        else:
            since = rng.randint(CURRENT_SYSTEM_YEAR, NOW.year)
        joined = random_instant(rng, since, datetime(FIRST_YEAR, 1, 1, tzinfo=timezone.utc))

        for year in range(since, NOW.year + 1):
            pool = LEGACY_CODES[year] if year < CURRENT_SYSTEM_YEAR else current_codes
            for code in rng.sample(pool, k=rng.randint(0, 2)):
                order_id = str(uuid.UUID(int=rng.getrandbits(128), version=1))
                redemptions.append((email, code, order_id, random_instant(rng, year, joined)))

        customers.append({"email": email, "customer_since": since})

    redemptions.sort(key=lambda r: r[3])
    lines = [
        "-- Generated by scripts/generate-promo-seed.py. Do not edit by hand.",
        "",
        "INSERT INTO promotions.promo_code (code, percent_off, kind) VALUES",
        ",\n".join(f"    ({sql_str(c)}, {pct}, {sql_str(kind)})"
                   for c, pct, kind in [(c, pct, "percent") for c, pct in PROMO_CODES] + NEW_PROMO_CODES) + ";",
        "",
        "INSERT INTO promotions.redemption (email, code, order_id, created_at) VALUES",
        ",\n".join(f"    ({sql_str(e)}, {sql_str(c)}, {sql_str(o)}, {sql_str(t.isoformat())})"
                   for e, c, o, t in redemptions) + ";",
    ]
    (ROOT / "src/postgres/promo-seed.sql").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ROOT / "src/load-generator/returning_customers.json").write_text(
        json.dumps(customers, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    legacy_codes = {c for codes in LEGACY_CODES.values() for c in codes}
    with_legacy = {e for e, c, _, _ in redemptions if c in legacy_codes}
    print(f"{len(customers)} customers, {len(redemptions)} redemptions, "
          f"{len(with_legacy)} customers have used a special-character code")


if __name__ == "__main__":
    main()
