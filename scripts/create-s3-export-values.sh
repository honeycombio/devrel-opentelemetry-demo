#!/bin/bash
# Generates skaffold-config/s3-export-values.yaml (gitignored).
#
# When TELEMETRY_S3_BUCKET is set (see .skaffold.env), the overlay adds an
# awss3 exporter (OTLP JSON, UTC-partitioned keys) to the collector's
# traces/logs/metrics pipelines and enables kubeletstats pod/container
# metrics for the duration of the capture. When unset or empty, it writes
# an empty overlay so the deploy is byte-identical to a deploy without
# this feature — that makes an accidental merge of this branch harmless.
#
# Invoked as a skaffold `before` deploy hook; safe to run standalone.
#
# NOTE (Helm list semantics): later values files REPLACE lists, so each
# pipeline's exporter/processor lists must be restated in full. They are
# read from skaffold-config/demo-values.yaml at generation time, with awss3
# and batch appended, so they cannot drift from it. Receivers are
# deliberately NOT declared so chart-default metrics receivers keep
# deep-merging in.
#
# NOTE (batch processor required): awss3exporter v0.151.0 unconditionally
# indexes ResourceMetrics/ResourceLogs/ResourceSpans .At(0) with no length
# check, so an empty batch (e.g. a kubeletstats scrape with nothing new)
# panics and crash-loops the collector. `batch` never forwards an empty
# batch downstream, so it must run last in every pipeline that feeds awss3.

set -e

OUT="skaffold-config/s3-export-values.yaml"
BASE="skaffold-config/demo-values.yaml"

if [ -z "$TELEMETRY_S3_BUCKET" ]; then
  echo "{}" > "$OUT"
  echo "s3-export: TELEMETRY_S3_BUCKET not set; wrote empty overlay ($OUT)."
  exit 0
fi

export TELEMETRY_S3_REGION="${TELEMETRY_S3_REGION:-us-east-1}"
export TELEMETRY_S3_PREFIX="${USER}"

python3 - "$BASE" "$OUT" << 'PY'
import os
import sys

import yaml

base_path, out_path = sys.argv[1], sys.argv[2]

with open(base_path) as f:
    base = yaml.safe_load(f)
base_pipelines = base["opentelemetry-collector"]["config"]["service"]["pipelines"]


def with_item(items, extra):
    """Return items with extra appended unless already present."""
    return list(items) if extra in items else list(items) + [extra]


pipelines = {}
for name in ("traces", "logs", "metrics"):
    p = base_pipelines[name]
    # batch goes last, so it never forwards an empty batch to awss3.
    processors = [x for x in p.get("processors", []) if x != "batch"] + ["batch"]
    pipelines[name] = {
        "exporters": with_item(p.get("exporters", []), "awss3"),
        "processors": processors,
    }

overlay = {
    "opentelemetry-collector": {
        "presets": {"kubeletMetrics": {"enabled": True}},
        "config": {
            "processors": {"batch": {}},
            "exporters": {
                "awss3": {
                    "s3uploader": {
                        "region": os.environ["TELEMETRY_S3_REGION"],
                        "s3_bucket": os.environ["TELEMETRY_S3_BUCKET"],
                        "s3_prefix": os.environ["TELEMETRY_S3_PREFIX"],
                        "s3_partition_timezone": "UTC",
                    },
                    "marshaler": "otlp_json",
                }
            },
            "service": {"pipelines": pipelines},
        },
    }
}

with open(out_path, "w") as f:
    f.write("# GENERATED by scripts/create-s3-export-values.sh — do not edit or commit.\n")
    yaml.safe_dump(overlay, f, sort_keys=False)
PY

echo "s3-export: capture ON -> s3://${TELEMETRY_S3_BUCKET}/${USER}/ (${TELEMETRY_S3_REGION}), overlay $OUT"
